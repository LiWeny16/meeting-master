export type MessageKey = keyof typeof messages.en;

export function isTranslatedMessage(key: MessageKey, value: string): boolean {
  return Object.values(messages).some((locale) => locale[key] === value);
}

export function useI18n() {
  const { preferences, setLocale } = useThemePreferences();
  const locale = preferences.locale;
  const t = useMemo(() => (key: MessageKey) => messages[locale][key], [locale]);
  return { locale, setLocale, t };
}
